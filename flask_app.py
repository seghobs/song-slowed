from io import BytesIO
from pathlib import Path
from urllib.parse import quote
from flask import Flask, Request, jsonify, request, send_file
from audio_engine import AudioError, convert, MAX_BYTES, FORMATS, listening_copy

app = Flask(__name__)
app.config['MAX_CONTENT_LENGTH'] = MAX_BYTES + 1024 * 1024


class AudioRequest(Request):
    @property
    def max_content_length(self):
        return (1024 * 1024 * 1024 + 1024 * 1024) if self.path == '/api/listen' else app.config['MAX_CONTENT_LENGTH']


app.request_class = AudioRequest


@app.get('/')
def index():
    return send_file(Path(__file__).parent / 'static' / 'index.html')


@app.errorhandler(413)
def too_large(error):
    return jsonify(detail='Dosya en fazla 150 MB olabilir.'), 413


@app.post('/api/process')
def process():
    file = request.files.get('file')
    if file is None:
        return jsonify(detail='Bir ses dosyası seçin.'), 400
    output_format = request.form.get('output_format', 'wav')
    metadata = {}
    try:
        data = convert(file.stream, file.filename, request.form.get('speed', '1'), output_format, request.form.get('profile', 'auto'), metadata)
    except AudioError as error:
        return jsonify(detail=str(error)), 400
    suffix, mime, _ = FORMATS[output_format]
    response = send_file(BytesIO(data), mimetype=mime, as_attachment=True, download_name='tempo.' + suffix)
    response.headers['X-Tempo-Profile'] = metadata['profile']
    response.headers['X-Tempo-Reason'] = quote(metadata['reason'])
    return response


@app.post('/api/listen')
def listen():
    # This endpoint accepts the larger files generated by the renderer.
    file = request.files.get('file')
    if file is None:
        return jsonify(detail='Bir ses dosyası seçin.'), 400
    try:
        data = listening_copy(file.stream, file.filename)
    except AudioError as error:
        return jsonify(detail=str(error)), 400
    return send_file(BytesIO(data), mimetype='audio/wav')


if __name__ == '__main__':
    app.run(host='127.0.0.1', port=8765, debug=False)
